//Function. Функция с параметрами

function sayHello1(name) {
    console.log('Hello ' + name)
};

function sayBye1(name) {
    console.log('Bye ' + name)
};

sayHello1('Yana');
sayHello1('Alex');
sayBye1('Yana');
sayBye1('Alex');